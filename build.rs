// Sets LOGIX_ENGINE_BUILD_VERSION, the engine version reported by get_engine_info
// and --version. Release builds pass it in the LOGIX_ENGINE_BUILD_VERSION env var
// (the release tag, yyyy-mm-dd or yyyy-mm-dd-N). Other builds use today's
// UTC date.
//
// Also picks the board catalog to build in (see catalog_files): catalog/, the
// pinned copy of Logix Catalog, or the clone LOGIX_ENGINE_DEV_CATALOG names.

use std::path::{Path, PathBuf};
use std::process::Command;
use std::time::{SystemTime, UNIX_EPOCH};

fn main() {
    catalog_files();
    println!("cargo:rerun-if-env-changed=LOGIX_ENGINE_BUILD_VERSION");
    let version = match std::env::var("LOGIX_ENGINE_BUILD_VERSION") {
        Ok(v) if !v.is_empty() => {
            if !is_release_tag(&v) {
                panic!("LOGIX_ENGINE_BUILD_VERSION must be yyyy-mm-dd or yyyy-mm-dd-N, got {v:?}");
            }
            v
        }
        _ => today_utc(),
    };
    println!("cargo:rustc-env=LOGIX_ENGINE_BUILD_VERSION={version}");
}

fn is_release_tag(v: &str) -> bool {
    let (date, suffix) = match v.get(10..) {
        Some("") => (v, None),
        Some(rest) => match rest.strip_prefix('-') {
            Some(n) => (&v[..10], Some(n)),
            None => return false,
        },
        None => return false,
    };
    let b = date.as_bytes();
    let date_ok = b.len() == 10
        && b[4] == b'-'
        && b[7] == b'-'
        && b.iter()
            .enumerate()
            .all(|(i, c)| i == 4 || i == 7 || c.is_ascii_digit());
    let suffix_ok = suffix.is_none_or(|n| {
        !n.is_empty() && !n.starts_with('0') && n.bytes().all(|c| c.is_ascii_digit())
    });
    date_ok && suffix_ok
}

fn today_utc() -> String {
    let secs = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .expect("clock before 1970")
        .as_secs();
    let (y, m, d) = civil_from_days((secs / 86_400) as i64);
    format!("{y:04}-{m:02}-{d:02}")
}

// Days since 1970-01-01 to a calendar date (Howard Hinnant's algorithm).
fn civil_from_days(z: i64) -> (i64, u32, u32) {
    let z = z + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z.rem_euclid(146_097);
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = (doy - (153 * mp + 2) / 5 + 1) as u32;
    let m = if mp < 10 { mp + 3 } else { mp - 9 } as u32;
    let y = yoe + era * 400 + i64::from(m <= 2);
    (y, m, d)
}

// Writes $OUT_DIR/catalog_files.rs: the catalog's board files (by ID, sorted),
// the FPGA files (by family, sorted) and the board schema, all as include_str!, plus where they came
// from. From LOGIX_ENGINE_DEV_CATALOG, an absolute path to a logix-catalog
// clone, when set (local builds; the version is the clone's commit and date,
// marked local), else from catalog/ (its version in catalog/SOURCE.json).
fn catalog_files() {
    println!("cargo:rerun-if-env-changed=LOGIX_ENGINE_DEV_CATALOG");
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let (dir, local) = match std::env::var("LOGIX_ENGINE_DEV_CATALOG") {
        Ok(d) if !d.is_empty() => {
            let d = PathBuf::from(d);
            if !d.is_absolute() || !d.join("boards").is_dir() || !d.join("fpgas").is_dir() {
                panic!(
                    "LOGIX_ENGINE_DEV_CATALOG must be the absolute path of a logix-catalog clone (with boards/ and fpgas/), got {}",
                    d.display()
                );
            }
            (d, true)
        }
        _ => (manifest.join("catalog"), false),
    };
    let boards = json_files(&dir.join("boards"));
    let fpgas = json_files(&dir.join("fpgas"));
    let (commit, date) = if local {
        let git = |args: &[&str]| {
            Command::new("git")
                .arg("-C")
                .arg(&dir)
                .args(args)
                .env("TZ", "UTC")
                .output()
                .ok()
                .filter(|o| o.status.success())
                .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_string())
                .unwrap_or_default()
        };
        (
            git(&["rev-parse", "--short=7", "HEAD"]),
            git(&["log", "-1", "--date=format-local:%Y-%m-%d", "--format=%cd"]),
        )
    } else {
        let source = dir.join("SOURCE.json");
        println!("cargo:rerun-if-changed={}", source.display());
        let text = std::fs::read_to_string(&source).expect("catalog/SOURCE.json");
        (json_string(&text, "commit"), json_string(&text, "date"))
    };
    let lit = |p: &Path| format!("include_str!({:?})", p.display().to_string());
    let mut out = String::from("// Generated by build.rs: the catalog this engine builds in.\n");
    for (name, files) in [("BOARD_FILES", &boards), ("FPGA_FILES", &fpgas)] {
        out += &format!("pub const {name}: &[(&str, &str)] = &[\n");
        for (id, path) in files {
            println!("cargo:rerun-if-changed={}", path.display());
            out += &format!("    ({id:?}, {}),\n", lit(path));
        }
        out += "];\n";
    }
    let schema = dir.join("schemas/logix-board-v1.json");
    println!("cargo:rerun-if-changed={}", schema.display());
    out += &format!("pub const BOARD_SCHEMA: &str = {};\n", lit(&schema));
    out += &format!(
        "pub const COMMIT: &str = {commit:?};\npub const DATE: &str = {date:?};\npub const LOCAL: bool = {local};\n"
    );
    let dest = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("catalog_files.rs");
    std::fs::write(dest, out).expect("write catalog_files.rs");
}

// A folder's .json files as (name without .json, path), sorted by name.
fn json_files(dir: &Path) -> Vec<(String, PathBuf)> {
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut files: Vec<(String, PathBuf)> = std::fs::read_dir(dir)
        .unwrap_or_else(|e| panic!("can't read {}: {e}", dir.display()))
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.extension().is_some_and(|x| x == "json"))
        .map(|p| (p.file_stem().unwrap().to_string_lossy().into_owned(), p))
        .collect();
    files.sort();
    files
}

// The string value of a top-level "key" in a small JSON object, without a
// JSON parser (build scripts have no dependencies here).
fn json_string(text: &str, key: &str) -> String {
    let pat = format!("\"{key}\"");
    let rest = &text[text
        .find(&pat)
        .unwrap_or_else(|| panic!("catalog/SOURCE.json: no {key}"))
        + pat.len()..];
    let start = rest.find('"').expect("a string value") + 1;
    let end = rest[start..].find('"').expect("a closed string") + start;
    rest[start..end].to_string()
}
